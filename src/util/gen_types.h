#pragma once

#include <stdint.h>

/* Types for general use */
typedef unsigned char  uchar;
typedef unsigned short ushort;
typedef unsigned int   uint;
typedef unsigned long  ulong;

/* Integer types for byte alignment */
typedef uchar  u8;
typedef ushort u16;
typedef uint   u32;
typedef ulong  u64;

typedef char  i8;
typedef short i16;
typedef int   i32;
typedef long  i64;